import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const windowsRoot = resolve(scriptDir, '..');
const repoRoot = resolve(windowsRoot, '../..');

const pubspec = await readFile(join(repoRoot, 'pubspec.yaml'), 'utf8');
const versionMatch = pubspec.match(/^version:\s*(\d+\.\d+\.\d+)(?:\+(\d+))?\s*$/m);
if (!versionMatch) {
  throw new Error('Unable to parse application version from pubspec.yaml');
}
const appVersion = versionMatch[1];
const buildNumber = Number(versionMatch[2] ?? '0');

const contract = JSON.parse(await readFile(join(repoRoot, 'assets/public-contract.json'), 'utf8'));
const q = (value) => JSON.stringify(String(value));
const arr = (items) => items.map(q).join(', ');

const generatedCs = `// <auto-generated />
// Generated from assets/public-contract.json and pubspec.yaml by scripts/sync-assets.mjs.
#nullable enable

namespace Park.Core;

public sealed record LanguageSpec(string Id, string Name, string TranslationId);

public static class PublicContract
{
    public const string AppVersion = ${q(appVersion)};
    public const int BuildNumber = ${buildNumber};
    public const int ApiVersion = ${Number(contract.sourceProtocol.apiVersion)};

    public static IReadOnlyList<string> SourceTypes { get; } = [${arr(contract.sourceProtocol.types)}];
    public static IReadOnlyList<string> MediaKinds { get; } = [${arr(contract.sourceProtocol.mediaKinds)}];
    public static IReadOnlyList<string> Categories { get; } = [${arr(contract.sourceProtocol.categories)}];
    public static IReadOnlyList<string> ReverseSearchCategories { get; } = [${arr(contract.sourceProtocol.reverseSearchCategories)}];

    public static IReadOnlyList<string> DefaultDomainOrder { get; } = [${arr(contract.domains.order)}];
    public static IReadOnlySet<string> TwoDDomains { get; } = new HashSet<string>(StringComparer.Ordinal) { ${arr(contract.domains.dimension.twoD)} };
    public static IReadOnlySet<string> ThreeDDomains { get; } = new HashSet<string>(StringComparer.Ordinal) { ${arr(contract.domains.dimension.threeD)} };
    public static IReadOnlySet<string> ImageMediaDomains { get; } = new HashSet<string>(StringComparer.Ordinal) { ${arr(contract.domains.media.image)} };
    public static IReadOnlySet<string> VideoMediaDomains { get; } = new HashSet<string>(StringComparer.Ordinal) { ${arr(contract.domains.media.video)} };
    public static IReadOnlySet<string> VoiceMediaDomains { get; } = new HashSet<string>(StringComparer.Ordinal) { ${arr(contract.domains.media.voice)} };

    public static IReadOnlyList<LanguageSpec> Languages { get; } =
    [
${contract.languages.map((l) => `        new(${q(l.id)}, ${q(l.name)}, ${q(l.translationId)}),`).join('\n')}
    ];

    public const string OfficialRepositoryBase = ${q(contract.officialRepositories.base)};
    public static IReadOnlyList<string> OfficialChannels { get; } = [${arr(contract.officialRepositories.channels)}];
    public const string OfficialTagTranslationsChannel = ${q(contract.officialRepositories.tagTranslations)};
}
`;

const generatedDir = join(windowsRoot, 'src/Park.Core/Generated');
await mkdir(generatedDir, { recursive: true });
await writeFile(join(generatedDir, 'PublicContract.g.cs'), generatedCs, 'utf8');

const assetsOut = join(windowsRoot, 'assets');
await rm(assetsOut, { recursive: true, force: true });
await mkdir(assetsOut, { recursive: true });

for (const folder of ['runtime', 'sources', 'i18n', 'tag_translations', 'worldbook_terms']) {
  await cp(join(repoRoot, 'assets', folder), join(assetsOut, folder), { recursive: true });
}
await cp(join(windowsRoot, 'locales'), join(assetsOut, 'windows-locales'), { recursive: true });
await cp(join(repoRoot, 'LICENSE'), join(assetsOut, 'LICENSE'));
await cp(join(repoRoot, 'docs/licenses'), join(assetsOut, 'licenses'), { recursive: true });

console.log(`Synced Windows shared assets and generated PublicContract.g.cs (v${appVersion}+${buildNumber})`);
